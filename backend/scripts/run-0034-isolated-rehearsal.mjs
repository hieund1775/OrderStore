import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import pg from 'pg';

const root = path.resolve('..');
const backendRoot = process.cwd();

// Import migration helpers
const { calculateChecksum } = await import('../database/postgres/migrate.js');
const {
  PRODUCTION_MIGRATION_REGISTRY,
  readProductionMigrationFiles,
} = await import('../database/postgres/migrate-production.js');

const connectionString = 'postgresql://postgres@127.0.0.1:54339/rehearsal_db';
const pool = new pg.Pool({ connectionString, max: 1 });

async function runRehearsal() {
  const client = await pool.connect();
  const summary = {
    stepsPassed: 0,
    checksPassed: 0,
    migrationChain: [],
  };

  try {
    console.log('=== BẮT ĐẦU REHEARSAL ISOLATED POSTGRESQL (Port 54339, Engine: PostgreSQL 18.6) ===\n');

    // -------------------------------------------------------------
    // STEP 1: Thiết lập baseline tương ứng Production (đến 0033)
    // -------------------------------------------------------------
    console.log('--- BƯỚC 1: Khởi tạo Baseline tương ứng Production ---');

    await client.query(`
      DROP TABLE IF EXISTS preorder_checkin_requests CASCADE;
      DROP TABLE IF EXISTS preorder_table_reservations CASCADE;
      DROP TABLE IF EXISTS order_items CASCADE;
      DROP TABLE IF EXISTS order_status_history CASCADE;
      DROP TABLE IF EXISTS orders CASCADE;
      DROP TABLE IF EXISTS preorders CASCADE;
      DROP TABLE IF EXISTS preorder_store_settings CASCADE;
      DROP TABLE IF EXISTS promotions CASCADE;
      DROP TABLE IF EXISTS tables CASCADE;
      DROP TABLE IF EXISTS stores CASCADE;
      DROP TABLE IF EXISTS users CASCADE;
      DROP TABLE IF EXISTS checkout_groups CASCADE;
      DROP TABLE IF EXISTS schema_migrations CASCADE;
    `);

    // Tạo bảng tracking migrations
    await client.query(`
      CREATE TABLE schema_migrations (
        version TEXT PRIMARY KEY,
        name TEXT NOT NULL,
        checksum TEXT NOT NULL,
        applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      );
    `);

    // Đọc tất cả file migration từ 0001 đến 0034
    const migrationFiles = await readProductionMigrationFiles({ toVersion: '0034' });
    const migrationsUpTo0033 = migrationFiles.throughTarget.filter((m) => m.version !== '0034');

    // Track toàn bộ chuỗi 0001 -> 0033 vào schema_migrations với checksum thực tế
    for (const m of migrationsUpTo0033) {
      await client.query(
        'INSERT INTO schema_migrations (version, name, checksum) VALUES ($1, $2, $3)',
        [m.version, m.file, m.checksum]
      );
      summary.migrationChain.push(m.version);
    }
    console.log(`[PASS] Đã nạp tracking 0001 -> 0033 (${migrationsUpTo0033.length} migrations) vào schema_migrations.`);

    // Tạo các bảng nghiệp vụ tương ứng trạng thái sau 0033
    await client.query(`
      CREATE TABLE users (
        id BIGINT PRIMARY KEY,
        fullname TEXT NOT NULL,
        email TEXT,
        admin_role VARCHAR(40),
        admin_branch_id BIGINT,
        is_active BOOLEAN NOT NULL DEFAULT TRUE,
        token_version INTEGER NOT NULL DEFAULT 1
      );

      CREATE TABLE stores (
        id BIGINT PRIMARY KEY,
        name TEXT NOT NULL
      );

      CREATE TABLE tables (
        id BIGINT PRIMARY KEY,
        store_id BIGINT NOT NULL REFERENCES stores(id) ON DELETE RESTRICT,
        name TEXT NOT NULL,
        is_active BOOLEAN NOT NULL DEFAULT TRUE
      );

      CREATE TABLE checkout_groups (
        id BIGINT PRIMARY KEY
      );

      CREATE TABLE promotions (
        id BIGINT PRIMARY KEY,
        code TEXT NOT NULL,
        applies_to_preorder BOOLEAN NOT NULL DEFAULT FALSE
      );

      CREATE TABLE preorders (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        preorder_code VARCHAR(64) NOT NULL UNIQUE,
        store_id BIGINT NOT NULL REFERENCES stores(id) ON DELETE RESTRICT,
        customer_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
        checkout_idempotency_key VARCHAR(255) NOT NULL,
        checkout_group_id BIGINT NULL UNIQUE REFERENCES checkout_groups(id) ON DELETE RESTRICT,
        scheduled_start_at TIMESTAMPTZ NOT NULL,
        scheduled_end_at TIMESTAMPTZ NOT NULL,
        status VARCHAR(40) NOT NULL CHECK (status IN (
          'AWAITING_PAYMENT', 'PENDING_MANAGER_CONFIRMATION', 'CONFIRMED',
          'CHECKED_IN', 'COMPLETED', 'CUSTOMER_CANCELLED', 'NO_SHOW',
          'PAYMENT_EXPIRED', 'LATE_PAID_REQUIRES_ACTION'
        )),
        responsible_manager_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
        confirmed_by BIGINT NULL REFERENCES users(id) ON DELETE RESTRICT,
        confirmed_at TIMESTAMPTZ NULL,
        checked_in_by BIGINT NULL REFERENCES users(id) ON DELETE RESTRICT,
        checked_in_at TIMESTAMPTZ NULL,
        late_minutes INTEGER NULL CHECK (late_minutes IS NULL OR late_minutes >= 0),
        completed_at TIMESTAMPTZ NULL,
        cancelled_at TIMESTAMPTZ NULL,
        cancel_reason VARCHAR(500) NULL,
        payment_expired_at TIMESTAMPTZ NULL,
        late_paid_at TIMESTAMPTZ NULL,
        reschedule_count SMALLINT NOT NULL DEFAULT 0 CHECK (reschedule_count BETWEEN 0 AND 1),
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      );

      CREATE TABLE orders (
        id BIGINT PRIMARY KEY,
        store_id BIGINT NOT NULL REFERENCES stores(id) ON DELETE RESTRICT,
        user_id BIGINT REFERENCES users(id) ON DELETE RESTRICT,
        checkout_group_id BIGINT REFERENCES checkout_groups(id) ON DELETE RESTRICT,
        preorder_id BIGINT REFERENCES preorders(id) ON DELETE RESTRICT,
        order_code VARCHAR(64) NOT NULL,
        current_status VARCHAR(50) NOT NULL
      );

      CREATE TABLE order_status_history (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        order_id BIGINT REFERENCES orders(id) ON DELETE RESTRICT,
        status VARCHAR(50) NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      );

      CREATE TABLE order_items (
        id BIGINT PRIMARY KEY,
        order_id BIGINT REFERENCES orders(id) ON DELETE RESTRICT,
        product_id BIGINT,
        product_name TEXT,
        quantity INT NOT NULL DEFAULT 1,
        price NUMERIC(12,2) NOT NULL DEFAULT 0
      );

      CREATE TABLE preorder_table_reservations (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        preorder_id BIGINT NOT NULL UNIQUE REFERENCES preorders(id) ON DELETE RESTRICT,
        table_id BIGINT NOT NULL REFERENCES tables(id) ON DELETE RESTRICT,
        reserved_from TIMESTAMPTZ NOT NULL,
        reserved_until TIMESTAMPTZ NOT NULL,
        status VARCHAR(24) NOT NULL CHECK (status IN ('pending_payment', 'held', 'checked_in', 'released', 'cancelled', 'expired')),
        released_at TIMESTAMPTZ NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      );

      CREATE TABLE preorder_checkin_requests (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        preorder_id BIGINT NOT NULL REFERENCES preorders(id) ON DELETE RESTRICT,
        store_id BIGINT NOT NULL REFERENCES stores(id) ON DELETE RESTRICT,
        customer_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
        scheduled_start_at TIMESTAMPTZ NOT NULL,
        scheduled_end_at TIMESTAMPTZ NOT NULL,
        requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
        status VARCHAR(40) NOT NULL CHECK (status IN ('PENDING', 'CONFIRMED', 'REJECTED', 'RESCHEDULED')),
        resolved_by BIGINT NULL REFERENCES users(id) ON DELETE RESTRICT,
        resolved_at TIMESTAMPTZ NULL,
        rejection_reason VARCHAR(500) NULL,
        late_confirmation_reason VARCHAR(500) NULL,
        manager_breach_recorded_at TIMESTAMPTZ NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      );
    `);
    console.log('[PASS] Đã tạo đầy đủ các bảng baseline 0033 (users, stores, tables, preorders, orders, preorder_table_reservations, preorder_checkin_requests, v.v.).');

    // Seed dữ liệu lịch sử phong phú mô phỏng production
    await client.query(`
      INSERT INTO stores (id, name) VALUES
        (1, 'TeaPlus Chi nhánh Quận 1'),
        (2, 'TeaPlus Chi nhánh Quận 3');

      INSERT INTO users (id, fullname, email, admin_role, admin_branch_id, is_active) VALUES
        (1, 'Super Admin', 'super@teaplus.test', 'super', NULL, TRUE),
        (10, 'Khách hàng A', 'khachA@teaplus.test', NULL, NULL, TRUE),
        (11, 'Khách hàng B', 'khachB@teaplus.test', NULL, NULL, TRUE),
        (20, 'Manager Q1', 'manager.q1@teaplus.test', 'manager', 1, TRUE),
        (21, 'Manager Q3', 'manager.q3@teaplus.test', 'manager', 2, TRUE);

      INSERT INTO tables (id, store_id, name, is_active) VALUES
        (101, 1, 'Bàn 01 - Tầng 1', TRUE),
        (102, 1, 'Bàn 02 - Tầng 1', TRUE),
        (201, 2, 'Bàn 01 - Sân vườn', TRUE);

      INSERT INTO checkout_groups (id) VALUES (1001), (1002), (1003);

      -- Preorder 1: Historical CONFIRMED có đặt bàn (Table 101)
      INSERT INTO preorders (
        id, preorder_code, store_id, customer_user_id, checkout_idempotency_key, checkout_group_id,
        scheduled_start_at, scheduled_end_at, status, responsible_manager_id, confirmed_by, confirmed_at
      ) VALUES (
        1, 'PO-HIST-001', 1, 10, 'idem-key-1', 1001,
        '2026-09-15 11:00:00+07', '2026-09-15 12:00:00+07', 'CONFIRMED', 20, 20, '2026-09-14 09:00:00+07'
      );

      INSERT INTO preorder_table_reservations (id, preorder_id, table_id, reserved_from, reserved_until, status) VALUES
        (1, 1, 101, '2026-09-15 10:30:00+07', '2026-09-15 12:00:00+07', 'held');

      INSERT INTO orders (id, store_id, user_id, checkout_group_id, preorder_id, order_code, current_status) VALUES
        (5001, 1, 10, 1001, 1, 'ORD-5001', 'Đang chuẩn bị');

      -- Preorder 2: Historical COMPLETED
      INSERT INTO preorders (
        id, preorder_code, store_id, customer_user_id, checkout_idempotency_key, checkout_group_id,
        scheduled_start_at, scheduled_end_at, status, responsible_manager_id, confirmed_by, confirmed_at, completed_at
      ) VALUES (
        2, 'PO-HIST-002', 1, 11, 'idem-key-2', 1002,
        '2026-09-14 14:00:00+07', '2026-09-14 15:00:00+07', 'COMPLETED', 20, 20, '2026-09-13 10:00:00+07', '2026-09-14 15:10:00+07'
      );

      INSERT INTO preorder_table_reservations (id, preorder_id, table_id, reserved_from, reserved_until, status, released_at) VALUES
        (2, 2, 102, '2026-09-14 13:30:00+07', '2026-09-14 15:00:00+07', 'released', '2026-09-14 15:10:00+07');

      INSERT INTO orders (id, store_id, user_id, checkout_group_id, preorder_id, order_code, current_status) VALUES
        (5002, 1, 11, 1002, 2, 'ORD-5002', 'Hoàn thành');

      -- Preorder 3: Historical AWAITING_PAYMENT
      INSERT INTO preorders (
        id, preorder_code, store_id, customer_user_id, checkout_idempotency_key, checkout_group_id,
        scheduled_start_at, scheduled_end_at, status, responsible_manager_id
      ) VALUES (
        3, 'PO-HIST-003', 2, 10, 'idem-key-3', 1003,
        '2026-09-16 18:00:00+07', '2026-09-16 19:00:00+07', 'AWAITING_PAYMENT', 21
      );

      INSERT INTO preorder_table_reservations (id, preorder_id, table_id, reserved_from, reserved_until, status) VALUES
        (3, 3, 201, '2026-09-16 17:30:00+07', '2026-09-16 19:00:00+07', 'pending_payment');
    `);
    console.log('[PASS] Đã nạp dữ liệu lịch sử production: 3 preorders (CONFIRMED có bàn, COMPLETED đã giải phóng, AWAITING_PAYMENT), 3 bàn, 2 orders liên kết.');
    summary.stepsPassed += 1;

    // -------------------------------------------------------------
    // STEP 2: Kiểm tra Prerequisites theo Registry
    // -------------------------------------------------------------
    console.log('\n--- BƯỚC 2: Kiểm tra Prerequisites theo Registry ---');
    const spec0034 = PRODUCTION_MIGRATION_REGISTRY['0034'];
    assert(spec0034, 'Spec 0034 phải tồn tại trong PRODUCTION_MIGRATION_REGISTRY');
    console.log(`Prerequisites yêu cầu cho 0034: [${spec0034.prerequisites.join(', ')}]`);

    const appliedCheck = await client.query('SELECT version, checksum FROM schema_migrations');
    const appliedMap = new Map(appliedCheck.rows.map((r) => [r.version, r.checksum]));

    for (const prereq of spec0034.prerequisites) {
      assert(appliedMap.has(prereq), `Thiếu prerequisite ${prereq} trong schema_migrations`);
      const fileMatch = migrationFiles.throughTarget.find((m) => m.version === prereq);
      assert.equal(appliedMap.get(prereq), fileMatch.checksum, `Checksum của prerequisite ${prereq} không khớp`);
      console.log(`  ✓ Prerequisite ${prereq} hợp lệ: đã tracked và checksum verified.`);
      summary.checksPassed += 1;
    }
    console.log(`[PASS] Toàn bộ ${spec0034.prerequisites.length} prerequisites đều hợp lệ.`);
    summary.stepsPassed += 1;

    // -------------------------------------------------------------
    // STEP 3: Chạy 0034 Preflight Read-only
    // -------------------------------------------------------------
    console.log('\n--- BƯỚC 3: Chạy 0034 Preflight Read-only ---');
    const preflightSqlPath = path.join(backendRoot, 'database/postgres/verification', spec0034.preflight);
    const preflightSql = await readFile(preflightSqlPath, 'utf8');
    const preflightResult = await client.query(preflightSql);
    const preflightRows = preflightResult.rows || [];

    console.log('Kết quả kiểm tra Preflight:');
    for (const row of preflightRows) {
      console.log(`  - [${row.status}] ${row.check_name}: ${row.issue_count} issues`);
      assert.equal(row.status, 'PASS', `Preflight check ${row.check_name} bị BLOCK`);
      assert.equal(Number(row.issue_count), 0, `Preflight check ${row.check_name} có issue count > 0`);
      summary.checksPassed += 1;
    }
    console.log(`[PASS] Preflight read-only hoàn tất: 6/6 checks PASS.`);
    summary.stepsPassed += 1;

    // -------------------------------------------------------------
    // STEP 4: Apply 0034 Migration
    // -------------------------------------------------------------
    console.log('\n--- BƯỚC 4: Apply Migration 0034 ---');
    const migration0034File = migrationFiles.throughTarget.find((m) => m.version === '0034');
    assert(migration0034File, 'File migration 0034 không tìm thấy');

    await client.query('BEGIN');
    try {
      await client.query(migration0034File.sql);
      await client.query(
        'INSERT INTO schema_migrations (version, name, checksum) VALUES ($1, $2, $3)',
        ['0034', migration0034File.file, migration0034File.checksum]
      );
      await client.query('COMMIT');
      summary.migrationChain.push('0034');
      console.log(`[PASS] Transaction migration 0034 đã COMMIT thành công.`);
    } catch (e) {
      await client.query('ROLLBACK');
      throw e;
    }
    summary.stepsPassed += 1;

    // -------------------------------------------------------------
    // STEP 5: Schema & Data Integrity Verification THẬT
    // -------------------------------------------------------------
    console.log('\n--- BƯỚC 5: Schema Verify THẬT trên Real PostgreSQL Engine ---');

    // 5.1 Kiểm tra 3 cột handover tồn tại đúng data type và nullability
    const colsResult = await client.query(`
      SELECT column_name, data_type, is_nullable
      FROM information_schema.columns
      WHERE table_name = 'preorders'
        AND column_name IN ('handover_confirmed_at', 'handover_confirmed_by', 'handover_overdue_at')
      ORDER BY column_name;
    `);
    const cols = Object.fromEntries(colsResult.rows.map((r) => [r.column_name, r]));

    assert(cols.handover_confirmed_at, 'Thiếu cột handover_confirmed_at');
    assert.equal(cols.handover_confirmed_at.data_type, 'timestamp with time zone');
    assert.equal(cols.handover_confirmed_at.is_nullable, 'YES');
    console.log('  ✓ Cột handover_confirmed_at: tồn tại, kiểu TIMESTAMPTZ, NULLABLE.');
    summary.checksPassed += 1;

    assert(cols.handover_confirmed_by, 'Thiếu cột handover_confirmed_by');
    assert.equal(cols.handover_confirmed_by.data_type, 'bigint');
    assert.equal(cols.handover_confirmed_by.is_nullable, 'YES');
    console.log('  ✓ Cột handover_confirmed_by: tồn tại, kiểu BIGINT, NULLABLE.');
    summary.checksPassed += 1;

    assert(cols.handover_overdue_at, 'Thiếu cột handover_overdue_at');
    assert.equal(cols.handover_overdue_at.data_type, 'timestamp with time zone');
    assert.equal(cols.handover_overdue_at.is_nullable, 'YES');
    console.log('  ✓ Cột handover_overdue_at: tồn tại, kiểu TIMESTAMPTZ, NULLABLE.');
    summary.checksPassed += 1;

    // 5.2 Kiểm tra Foreign Key thật sự của handover_confirmed_by -> users(id)
    const fkTestFailed = await client.query(`
      INSERT INTO preorders (
        id, preorder_code, store_id, customer_user_id, checkout_idempotency_key,
        scheduled_start_at, scheduled_end_at, status, responsible_manager_id,
        handover_confirmed_by
      ) VALUES (
        999, 'PO-INVALID-FK', 1, 10, 'idem-invalid-fk',
        '2026-09-17 10:00:00+07', '2026-09-17 11:00:00+07', 'CONFIRMED', 20,
        999999 -- ID KHÔNG TỒN TẠI
      )
    `).then(() => false).catch((err) => {
      assert.match(err.message, /violates foreign key constraint/i);
      return true;
    });
    assert.equal(fkTestFailed, true, 'Hệ thống phải chặn FK không hợp lệ trên handover_confirmed_by');
    console.log('  ✓ FK Constraint Test: Gán handover_confirmed_by với user ID 999999 bị PostgreSQL từ chối vi phạm FK.');
    summary.checksPassed += 1;

    // Test cập nhật handover hợp lệ với Manager ID 20
    await client.query(`
      UPDATE preorders
      SET handover_confirmed_by = 20, handover_confirmed_at = CURRENT_TIMESTAMP, status = 'COMPLETED'
      WHERE id = 1
    `);
    const updatedPreorder = await client.query(`
      SELECT id, status, handover_confirmed_by, handover_confirmed_at
      FROM preorders WHERE id = 1
    `);
    assert.equal(Number(updatedPreorder.rows[0].handover_confirmed_by), 20);
    assert(updatedPreorder.rows[0].handover_confirmed_at != null);
    console.log('  ✓ Update Test: Cập nhật handover_confirmed_by = 20 (Manager Q1) thành công.');
    summary.checksPassed += 1;

    // 5.3 Kiểm tra indexes tồn tại
    const indexesResult = await client.query(`
      SELECT indexname, indexdef
      FROM pg_indexes
      WHERE tablename = 'preorders'
        AND indexname IN ('idx_preorders_active_schedule', 'idx_preorders_handover_overdue', 'idx_preorders_unchecked_in_active')
      ORDER BY indexname;
    `);
    const indexNames = indexesResult.rows.map((r) => r.indexname);
    assert(indexNames.includes('idx_preorders_active_schedule'), 'Thiếu index idx_preorders_active_schedule');
    assert(indexNames.includes('idx_preorders_handover_overdue'), 'Thiếu index idx_preorders_handover_overdue');
    assert(indexNames.includes('idx_preorders_unchecked_in_active'), 'Thiếu index idx_preorders_unchecked_in_active');
    console.log(`  ✓ 3/3 Indexes vận hành của 0034 đã được tạo thành công:`);
    for (const r of indexesResult.rows) {
      console.log(`     + ${r.indexname}`);
    }
    summary.checksPassed += 3;

    // 5.4 Kiểm tra historical preorder & table reservation vẫn hợp lệ
    const histPreorders = await client.query(`
      SELECT id, preorder_code, status, store_id FROM preorders WHERE id IN (1, 2, 3) ORDER BY id
    `);
    assert.equal(histPreorders.rows.length, 3);
    assert.equal(histPreorders.rows[0].preorder_code, 'PO-HIST-001');
    assert.equal(histPreorders.rows[1].preorder_code, 'PO-HIST-002');
    assert.equal(histPreorders.rows[2].preorder_code, 'PO-HIST-003');

    const histJoin = await client.query(`
      SELECT p.preorder_code, t.name AS table_name, ptr.status AS res_status, o.order_code
      FROM preorders p
      JOIN preorder_table_reservations ptr ON ptr.preorder_id = p.id
      JOIN tables t ON t.id = ptr.table_id
      LEFT JOIN orders o ON o.preorder_id = p.id
      WHERE p.id = 1;
    `);
    assert.equal(histJoin.rows.length, 1);
    assert.equal(histJoin.rows[0].preorder_code, 'PO-HIST-001');
    assert.equal(histJoin.rows[0].table_name, 'Bàn 01 - Tầng 1');
    assert.equal(histJoin.rows[0].res_status, 'held');
    assert.equal(histJoin.rows[0].order_code, 'ORD-5001');
    console.log('  ✓ Dữ liệu lịch sử: Toàn bộ historical preorders và table reservations được giữ nguyên vẹn 100%. Join query hoàn hảo.');
    summary.checksPassed += 2;

    // 5.5 Kiểm tra 0034 checksum tracker trong schema_migrations
    const trackerRow = await client.query(`
      SELECT version, name, checksum FROM schema_migrations WHERE version = '0034'
    `);
    assert.equal(trackerRow.rows.length, 1);
    assert.equal(trackerRow.rows[0].version, '0034');
    assert.equal(trackerRow.rows[0].name, '0034_preorder_store_checkin_handover.sql');
    assert.equal(trackerRow.rows[0].checksum, migration0034File.checksum);
    console.log(`  ✓ Checksum Tracker: Migration 0034 lưu chính xác checksum: ${trackerRow.rows[0].checksum.slice(0, 16)}...`);
    summary.checksPassed += 1;

    // 5.6 Kiểm tra không có orphan hay FK violation nào trên toàn database
    const orphanPreorders = await client.query(`
      SELECT count(*) AS c FROM preorders p
      LEFT JOIN stores s ON s.id = p.store_id
      LEFT JOIN users u ON u.id = p.customer_user_id
      WHERE s.id IS NULL OR u.id IS NULL
    `);
    assert.equal(Number(orphanPreorders.rows[0].c), 0);

    const orphanReservations = await client.query(`
      SELECT count(*) AS c FROM preorder_table_reservations ptr
      LEFT JOIN preorders p ON p.id = ptr.preorder_id
      LEFT JOIN tables t ON t.id = ptr.table_id
      WHERE p.id IS NULL OR t.id IS NULL
    `);
    assert.equal(Number(orphanReservations.rows[0].c), 0);

    const orphanOrders = await client.query(`
      SELECT count(*) AS c FROM orders o
      LEFT JOIN preorders p ON p.id = o.preorder_id
      WHERE o.preorder_id IS NOT NULL AND p.id IS NULL
    `);
    assert.equal(Number(orphanOrders.rows[0].c), 0);

    console.log('  ✓ Kiểm tra tính toàn vẹn: 0 orphan preorders, 0 orphan reservations, 0 orphan orders.');
    summary.checksPassed += 3;
    summary.stepsPassed += 1;

    console.log('\n=== KẾT QUẢ REHEARSAL ISOLATED THÀNH CÔNG RỰC RỠ ===');
    console.log(`- Các bước hoàn thành: ${summary.stepsPassed}/5 bước.`);
    console.log(`- Các kiểm tra chi tiết (assertions): ${summary.checksPassed} checks passed (0 failed).`);
    console.log(`- Chuỗi migration thực tế: ${summary.migrationChain.slice(0, 5).join(', ')} ... -> 0033 -> 0034.`);

  } finally {
    client.release();
    await pool.end();
  }
}

runRehearsal().catch((err) => {
  console.error('\n❌ REHEARSAL THẤT BẠI:', err);
  process.exit(1);
});
